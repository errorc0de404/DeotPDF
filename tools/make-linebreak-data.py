"""Generates src/PdfNotes.Text.Skia/LineBreakData.g.cs from the Unicode Character Database (roadmap P2 S1).

python -I tools/make-linebreak-data.py <folder with LineBreak.txt, EastAsianWidth.txt, emoji-data.txt, license.txt>

The files come from https://www.unicode.org/Public/UCD/latest/ucd/ (emoji-data.txt is in ucd/emoji/) and
https://www.unicode.org/license.txt, whose notice goes into the generated file as the license asks. Hangul syllables
(U+AC00..U+D7A3, H2/H3) are left out of the table: the line breaker computes them.
"""
import os
import re
import sys

CLASSES = ["XX", "BK", "CR", "LF", "NL", "SP", "ZW", "ZWJ", "CM", "WJ", "GL", "BA", "BB", "B2", "HY", "HH", "CB", "CL",
           "CP", "EX", "IN", "NS", "OP", "QU", "IS", "NU", "PO", "PR", "SY", "AI", "AK", "AL", "AP", "AS", "CJ", "EB", "EM",
           "H2", "H3", "HL", "ID", "JL", "JV", "JT", "RI", "SA", "SG", "VF", "VI"]


def entries(path):
    """(first, last, value) for every data line of a UCD property file."""
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = [p.strip() for p in line.split(";")[:2]]
        first, _, last = cps.partition("..")
        yield int(first, 16), int(last or first, 16), value


def version(path):
    """The version in the file header: '# LineBreak-18.0.0.txt', or '# Version: 18.0.0' in emoji-data.txt."""
    with open(path, encoding="utf-8") as f:
        head = "".join(f.readline() for _ in range(12))
    match = re.search(r"-(\d+\.\d+\.\d+)\.txt|Version: (\d+\.\d+(?:\.\d+)?)", head)
    return match.group(1) or match.group(2)


def runs(values):
    """Merges a full code point -> value list into (start, value) runs."""
    out = []
    for cp, v in enumerate(values):
        if not out or out[-1][1] != v:
            out.append((cp, v))
    return out


def main(folder):
    size = 0x110000
    classes = ["XX"] * size
    for first, last, value in entries(os.path.join(folder, "LineBreak.txt")):
        for cp in range(first, last + 1):
            classes[cp] = value
    for cp in range(0xAC00, 0xD7A4):
        assert classes[cp] == ("H2" if (cp - 0xAC00) % 28 == 0 else "H3"), hex(cp)
        classes[cp] = "H2"  # placeholder: one run, resolved in code
    east = [False] * size
    for first, last, value in entries(os.path.join(folder, "EastAsianWidth.txt")):
        if value in ("F", "W", "H"):
            for cp in range(first, last + 1):
                east[cp] = True
    pictographic = [False] * size
    for first, last, value in entries(os.path.join(folder, "emoji-data.txt")):
        if value == "Extended_Pictographic":
            for cp in range(first, last + 1):
                pictographic[cp] = True

    class_runs = runs(classes)
    unknown = sorted({v for _, v in class_runs} - set(CLASSES))
    if unknown:
        sys.exit(f"new line break classes: {unknown} (update CLASSES and the line breaker)")

    def flags(values):
        # Boundaries where the flag flips, starting from false at U+0000.
        return [cp for cp, v in runs(values) if cp > 0 or v]

    lb, ea, ep = (version(os.path.join(folder, f)) for f in ("LineBreak.txt", "EastAsianWidth.txt", "emoji-data.txt"))
    out = []
    w = out.append
    w("// <auto-generated> by tools/make-linebreak-data.py from the Unicode Character Database:")
    w(f"// LineBreak-{lb}.txt, EastAsianWidth-{ea}.txt, emoji-data-{ep}.txt. Do not edit by hand.")
    w("//")
    for line in open(os.path.join(folder, "license.txt"), encoding="utf-8").read().rstrip().splitlines():
        w(("// " + line).rstrip())
    w("// </auto-generated>")
    w("namespace PdfNotes.Text.LineBreaking;")
    w("")
    w("/// <summary>The Line_Break property values of UAX #14.</summary>")
    w("public enum LineBreakClass : byte")
    w("{")
    w("    " + ", ".join(CLASSES) + ",")
    w("}")
    w("")
    w("internal static class LineBreakData")
    w("{")
    w(f"    public const string UnicodeVersion = \"{lb}\";")
    w("")

    def table(name, kind, items, per_line):
        w(f"    public static ReadOnlySpan<{kind}> {name} =>")
        w("    [")
        for i in range(0, len(items), per_line):
            w("        " + ", ".join(items[i:i + per_line]) + ",")
        w("    ];")
        w("")

    w("    /// <summary>First code point of each run of <see cref=\"Classes\"/>.</summary>")
    table("Starts", "int", [f"0x{cp:X}" for cp, _ in class_runs], 12)
    w("    /// <summary>The Line_Break value of each run (U+AC00..U+D7A3 is computed: H2 or H3).</summary>")
    table("Classes", "byte", [str(CLASSES.index(v)) for _, v in class_runs], 32)
    w("    /// <summary>East_Asian_Width F, W or H: code points where the property turns on/off, starting off at U+0000.</summary>")
    table("EastAsian", "int", [f"0x{cp:X}" for cp in flags(east)], 12)
    w("    /// <summary>Extended_Pictographic: code points where the property turns on/off, starting off at U+0000.</summary>")
    table("Pictographic", "int", [f"0x{cp:X}" for cp in flags(pictographic)], 12)
    out[-1:] = []
    w("}")
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "PdfNotes.Text.Skia", "LineBreakData.g.cs")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(class_runs)} class runs, {len(flags(east))} east asian and {len(flags(pictographic))} pictographic boundaries -> {os.path.normpath(target)}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
